const bbox = (p: Poly) => {
  let x0 = 180, x1 = -180, y0 = 90, y1 = -90;
  for (let i = 0; i < p.length; i += 2) {
    x0 = Math.min(x0, p[i]); x1 = Math.max(x1, p[i]);
    y0 = Math.min(y0, p[i + 1]); y1 = Math.max(y1, p[i + 1]);
  }
  return [x0, x1, y0, y1] as const;
};

function inside(p: Poly, box: readonly number[], x: number, y: number) {
  if (x < box[0] || x > box[1] || y < box[2] || y > box[3]) return false;
  let c = false;
  for (let i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    const xi = p[i], yi = p[i + 1], xj = p[j], yj = p[j + 1];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

const landBoxes = LAND.map(bbox);
const holeBoxes = HOLES.map(bbox);

export function isLand(lon: number, lat: number) {
  if (HOLES.some((p, i) => inside(p, holeBoxes[i], lon, lat))) return false;
  return LAND.some((p, i) => inside(p, landBoxes[i], lon, lat));
}

/** Land dots on latitude rows (alternate rows offset) — the halftone look. Flat [lon, lat, …]. */
export function landDots(step = 1.5): number[] {
  const out: number[] = [];
  let row = 0;
  for (let lat = -56; lat <= 83; lat += step, row++) {
    const n = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / step));
    for (let j = 0; j < n; j++) {
      const lon = -180 + ((j + (row % 2) * 0.5) * 360) / n;
      if (isLand(lon, lat)) out.push(lon, lat);
    }
  }
  return out;
}

const D2R = Math.PI / 180;
export type Vec3 = [number, number, number];

/** lon 0 faces +z, east is +x, north is +y. */
export function toVec(lon: number, lat: number, r = 1): Vec3 {
  const la = lat * D2R, lo = lon * D2R;
  return [r * Math.cos(la) * Math.sin(lo), r * Math.sin(la), r * Math.cos(la) * Math.cos(lo)];
}

/** Great-circle arc from a to b, lifted off the surface in proportion to its length. */
export function arcPath(a: [number, number], b: [number, number], n = 48): Vec3[] {
  const va = toVec(a[0], a[1]);
  const vb = toVec(b[0], b[1]);
  const ang = Math.acos(Math.min(1, Math.max(-1, va[0] * vb[0] + va[1] * vb[1] + va[2] * vb[2])));
  const s = Math.sin(ang) || 1e-6;
  const lift = 0.05 + ang * 0.12;
  const pts: Vec3[] = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n;
    const wa = Math.sin((1 - t) * ang) / s;
    const wb = Math.sin(t * ang) / s;
    const h = 1 + Math.sin(Math.PI * t) * lift;
    pts.push([(va[0] * wa + vb[0] * wb) * h, (va[1] * wa + vb[1] * wb) * h, (va[2] * wa + vb[2] * wb) * h]);
  }
  return pts;
}

/**
 * Same rotation the WebGL globe applies (Euler XYZ: y = -lon0, then x = lat0), so a view centred on
 * [lon0, lat0] puts that point at +z. Used by the flat fallback to project dots onto a 2D canvas.
 */
export function view(v: Vec3, lon0: number, lat0: number): Vec3 {
  const t = -lon0 * D2R, a = lat0 * D2R;
  const x = v[0] * Math.cos(t) + v[2] * Math.sin(t);
  const z = -v[0] * Math.sin(t) + v[2] * Math.cos(t);
  return [x, v[1] * Math.cos(a) - z * Math.sin(a), v[1] * Math.sin(a) + z * Math.cos(a)];
}
